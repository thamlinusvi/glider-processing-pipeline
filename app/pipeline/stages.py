# ── Stage 2c: Fix CF Metadata ─────────────────────────────────────────────────
def fix_metadata_command(base_dir, deployment):
    """
    Run fix_trajectoryprofile_metadata.py natively (no Docker) on the profile
    NC files generated by Stage 2a.  Fixes cdm_data_type, featureType,
    cdm_trajectory_variables, cf_role attributes so QC doesn't reject them.

    Input/output:  gncutils_slocum_nc_output/<deployment>/profile/  (in-place)
    """
    nc_dir = os.path.join(base_dir, 'gncutils_slocum_nc_output', deployment, 'profile')
    script = os.path.join(base_dir, 'fix_trajectoryprofile_metadata.py')
    return (
        [sys.executable, script, nc_dir],
        base_dir,
        {'PYTHONIOENCODING': 'utf-8'},   # script uses emoji — force UTF-8 stdout
    )


# ── Stage 3: QARTOD QC ────────────────────────────────────────────────────────
def qc_command(base_dir, deployment):
    """
    Run the full rugliderqc QARTOD pipeline inside Docker.
    Input:  gncutils_slocum_nc_output/<deployment>/profile/
    Output: deployments/<year>/<deployment>/data/out/nc/sci-profile/delayed/
    """
    year       = _year(deployment)
    nc_in      = f'/home/glider/gncutils_slocum_nc_output/{deployment}/profile'
    nc_out     = (f'/home/glider/deployments/{year}/{deployment}/'
                  f'data/out/nc/sci-profile/delayed')
    cfg_dir    = '/home/glider/qc/config'
    log_dir    = f'/home/glider/deployments/{year}/{deployment}/proc-logs'

    # Run each rugliderqc script in sequence
    scripts = [
        f'mkdir -p {nc_out} {log_dir}',
        f'python /home/glider/rugliderqc/scripts/check_science_variables.py      -p {nc_in}',
        f'python /home/glider/rugliderqc/scripts/interpolate_depth.py            -p {nc_in}',
        f'python /home/glider/rugliderqc/scripts/check_duplicate_timestamps.py   -p {nc_in}',
        f'python /home/glider/rugliderqc/scripts/glider_qartod_qc.py             -p {nc_in} -c {cfg_dir}',
        f'python /home/glider/rugliderqc/scripts/ctd_hysteresis_test.py          -p {nc_in}',
        f'python /home/glider/rugliderqc/scripts/time_shift.py                   -p {nc_in}',
        f'python /home/glider/rugliderqc/scripts/data_gap_check.py               -p {nc_in}',
        f'python /home/glider/rugliderqc/scripts/add_derived_variables.py        -p {nc_in}',
        f'python /home/glider/rugliderqc/scripts/summarize_qartod_flags.py       -p {nc_in}',
        f'python /home/glider/rugliderqc/scripts/move_nc_files.py                -p {nc_in} -o {nc_out}',
    ]
    inner = ' && \\\n  '.join(scripts)
    return _docker_run(base_dir, inner), base_dir, None


# ── Stage 4: Report + Plots ───────────────────────────────────────────────────
def report_command(base_dir, deployment):
    """Generate HTML QC report then all plots using native Python."""
    report_cmd = [sys.executable, os.path.join(base_dir, 'qc_report.py'), deployment]
    plot_cmd   = [sys.executable, os.path.join(base_dir, 'plot_qc_data.py'), deployment]
    # Return report script first; plot runs as a second pass in StageCard
    return report_cmd, base_dir, None


def plot_command(base_dir, deployment):
    return [sys.executable, os.path.join(base_dir, 'plot_qc_data.py'), deployment], base_dir, None


