#!/usr/bin/env python
"""
Pre QAQC Config File Check.

Reads instrument metadata from a profile NetCDF file to determine which
QC config files (time_shift.yml, qctests.yml) are needed for the deployment.

Two modes:
  Analysis mode (default):
    python pre_qaqc_config_check.py <base_dir> <deployment>
    Scans the NC file, reports what was found, outputs a PREFLIGHT_JSON line
    at the end for the Electron frontend to parse.

  Apply mode:
    python pre_qaqc_config_check.py <base_dir> <deployment> --apply '<json>'
    Receives the JSON produced in analysis mode and writes the config files.
"""

import os
import sys
import json
import glob
import copy
import io
import base64
import argparse
import numpy as np
import xarray as xr
import yaml
import matplotlib
matplotlib.use('Agg')            # non-interactive backend — safe before any display is set
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
import matplotlib.ticker as mticker
import contextily as ctx
from pyproj import Transformer


# ── NC / instrument helpers ───────────────────────────────────────────────────

def find_profile_nc(base_dir, deployment):
    nc_dir  = os.path.join(base_dir, 'gncutils_slocum_nc_output', deployment, 'profile')
    ncfiles = sorted(glob.glob(os.path.join(nc_dir, '*.nc')))
    return ncfiles[0] if ncfiles else None


def read_instruments(nc_path):
    instruments = {}
    try:
        with xr.open_dataset(nc_path, decode_times=False) as ds:
            for var in list(ds.data_vars):
                if var.startswith('instrument_'):
                    instruments[var] = dict(ds[var].attrs)
    except Exception as e:
        print(f'ERROR: Could not read NC file: {e}', flush=True)
    return instruments


def detect_sensors(instruments):
    sensors = {'ctd': None, 'oxygen': None, 'ph': None}
    for name, attrs in instruments.items():
        low = name.lower()
        if 'rbrctd' in low or ('ctd' in low and 'rbr' in low):
            sensors['ctd'] = {'instrument_var': name,
                              'maker': attrs.get('maker', ''), 'model': attrs.get('model', '')}
        elif 'ctd' in low and sensors['ctd'] is None:
            sensors['ctd'] = {'instrument_var': name,
                              'maker': attrs.get('maker', ''), 'model': attrs.get('model', '')}
        elif 'optode' in low:
            sensors['oxygen'] = {'instrument_var': name,
                                 'maker': attrs.get('maker', ''), 'model': attrs.get('model', '')}
        elif 'ph' in low:
            sensors['ph'] = {'instrument_var': name,
                             'maker': attrs.get('maker', ''), 'model': attrs.get('model', '')}
    return sensors


def get_oxygen_vars(nc_path):
    skip = {'qartod', 'hysteresis', 'shifted', 'flag', 'instrument'}
    found = []
    try:
        with xr.open_dataset(nc_path, decode_times=False) as ds:
            for var in ds.data_vars:
                if 'oxygen' in var.lower() and not any(x in var for x in skip):
                    found.append(var)
    except Exception:
        pass
    return sorted(found)


# ── YAML builders ─────────────────────────────────────────────────────────────

def build_time_shift_yml(sensors, oxygen_vars):
    lines = ['time_shift:']
    for var in oxygen_vars:
        long_name = ('Time-lag Adjusted Dissolved Oxygen Saturation'
                     if 'saturation' in var.lower()
                     else 'Time-lag Adjusted Dissolved Oxygen')
        lines += [f'    {var}:',
                  f'        long_name: {long_name}',
                  f'        default_shift: 30']
    if sensors.get('ph'):
        lines += ['    sbe41n_ph_ref_voltage:',
                  '        long_name: Time-lag Adjusted pH Voltage',
                  '        default_shift: 30']
    return '\n'.join(lines) + '\n'


def build_qctests_yml(sensors):
    has_do  = sensors.get('oxygen') is not None
    has_ph  = sensors.get('ph')     is not None
    ctd_s   = sensors.get('ctd') or {}
    ctd_str = f'{ctd_s.get("maker","")} {ctd_s.get("model","")}'.strip() or 'detected'
    lines = [
        '# Auto-generated by Pre QAQC Config File Check',
        f'# Sensors: CTD={ctd_str}, O2={"yes" if has_do else "no"}, '
        f'pH={"yes" if has_ph else "no"}',
        'check_science_variables: true',
        'check_duplicate_timestamps: true',
        'qartod: true',
        'interp_depth: true',
        'hysteresis: true',
        'qartod_summary: true',
        f'time_shift: {"true" if (has_do or has_ph) else "false"}',
        f'add_derived_variables: {"true" if (has_do or has_ph) else "false"}',
    ]
    return '\n'.join(lines) + '\n'


def build_ctd_hysteresis_yml():
    """
    Returns a deployment-level ctd_hysteresis.yml seeded with the global defaults.

    Thresholds are expressed as fractions of the profile's data range:
      suspect_threshold  — fraction of range; profile flagged suspect if exceeded
      fail_threshold     — fraction of range; profile flagged fail if exceeded
      test_threshold     — minimum absolute data range required to run the test at all
                           (profiles with very small range, e.g. isothermal water, are skipped)

    Edit the values here to override the global defaults for this deployment.
    Global defaults live in rugliderqc/qc/config/ctd_hysteresis.yml.
    """
    lines = [
        '# Deployment-level CTD hysteresis test thresholds.',
        '# Generated by Pre QAQC Config File Check — edit to override global defaults.',
        '#',
        '# suspect_threshold / fail_threshold: fraction of profile data range.',
        '# test_threshold: minimum absolute data range to run the test',
        '#   (profiles with very small range, e.g. isothermal water, are skipped).',
        '',
        'conductivity_hysteresis_test:',
        '    suspect_threshold: .1',
        '    fail_threshold: .2',
        '    test_threshold: .05',
        '',
        'temperature_hysteresis_test:',
        '    suspect_threshold: .2',
        '    fail_threshold: .2',
        '    test_threshold: .1',
    ]
    return '\n'.join(lines) + '\n'


# ── Regional boundary helpers ─────────────────────────────────────────────────

def read_profile_positions(nc_dir):
    """
    Read profile_lat / profile_lon scalars from every NC file in nc_dir.
    Returns (lats, lons) as plain Python float lists.
    """
    lats, lons = [], []
    for f in sorted(glob.glob(os.path.join(nc_dir, '*.nc'))):
        try:
            with xr.open_dataset(f, decode_times=False) as ds:
                if 'profile_lat' not in ds.data_vars or 'profile_lon' not in ds.data_vars:
                    continue
                lat = float(ds['profile_lat'].values.flat[0])
                lon = float(ds['profile_lon'].values.flat[0])
                if not (np.isnan(lat) or np.isnan(lon)):
                    lats.append(lat)
                    lons.append(lon)
        except Exception:
            continue
    return lats, lons


def read_region_boundaries(base_dir):
    """
    Load qc/config/global_regional/regional_boundaries.yml.
    Returns (parsed_dict, full_path).
    """
    path = os.path.join(base_dir, 'qc', 'config', 'global_regional', 'regional_boundaries.yml')
    if not os.path.isfile(path):
        return None, path
    with open(path, 'r', encoding='utf-8') as f:
        return yaml.safe_load(f), path


def get_region_bounds(region_data, region_name='usvi'):
    """
    Extract (lon_min, lon_max, lat_min, lat_max) for region_name from parsed boundaries.
    Returns None if the region is not found.
    """
    for r in (region_data or {}).get('regions', []):
        if r.get('region') == region_name:
            bnd = r.get('boundaries', {})
            lons = bnd.get('longitude', [])
            lats = bnd.get('latitude', [])
            if lons and lats:
                return min(lons), max(lons), min(lats), max(lats)
    return None


def profiles_within_bounds(lats, lons, bounds):
    """
    Return True if every (lat, lon) pair falls inside bounds.
    bounds = (lon_min, lon_max, lat_min, lat_max)
    """
    lo_min, lo_max, la_min, la_max = bounds
    return all(lo_min <= lo <= lo_max and la_min <= la <= la_max
               for la, lo in zip(lats, lons))


def compute_proposed_boundary(lats, lons, buffer=0.5):
    """
    Buffered bounding box around the profile positions, rounded to 1 d.p.
    Returns (lat_min, lat_max, lon_min, lon_max).
    """
    return (round(min(lats) - buffer, 1),
            round(max(lats) + buffer, 1),
            round(min(lons) - buffer, 1),
            round(max(lons) + buffer, 1))


def build_updated_boundaries_yml(region_data, lat_min, lat_max, lon_min, lon_max,
                                  region_name='usvi'):
    """
    Return full regional_boundaries.yml content with the named region's polygon updated.
    The polygon is stored as four corner points (SW→SE→NE→NW order).
    """
    data = copy.deepcopy(region_data)
    for r in data.get('regions', []):
        if r.get('region') == region_name:
            r['boundaries']['longitude'] = [lon_min, lon_max, lon_max, lon_min]
            r['boundaries']['latitude']  = [lat_min, lat_min, lat_max, lat_max]
    return yaml.dump(data, default_flow_style=False, sort_keys=False)


def generate_region_map(lats, lons, current_bounds, proposed_bounds):
    """
    Render a satellite-imagery map (Esri World Imagery) showing the glider
    track and QARTOD region boundaries.
    current_bounds  = (lon_min, lon_max, lat_min, lat_max) or None
    proposed_bounds = (lon_min, lon_max, lat_min, lat_max)
    Returns the PNG encoded as a base-64 ASCII string.
    """
    p_lo_min, p_lo_max, p_la_min, p_la_max = proposed_bounds
    margin = 0.45  # degrees of padding around proposed box

    # ── Coordinate transforms ──────────────────────────────────────────────
    to_merc = Transformer.from_crs('EPSG:4326', 'EPSG:3857', always_xy=True)
    to_ll   = Transformer.from_crs('EPSG:3857', 'EPSG:4326', always_xy=True)

    def ll2m(lon, lat):
        return to_merc.transform(lon, lat)

    # Profile positions in Web Mercator
    xs, ys = to_merc.transform(list(lons), list(lats))

    # Map extent in Web Mercator
    ext_x0, ext_y0 = ll2m(p_lo_min - margin, p_la_min - margin)
    ext_x1, ext_y1 = ll2m(p_lo_max + margin, p_la_max + margin)

    # ── Figure ────────────────────────────────────────────────────────────
    fig, ax = plt.subplots(figsize=(8, 5.2), dpi=130)
    fig.patch.set_facecolor('#111111')
    ax.set_facecolor('#111111')

    ax.set_xlim(ext_x0, ext_x1)
    ax.set_ylim(ext_y0, ext_y1)

    # Satellite basemap — fetch AFTER setting limits so contextily picks the right zoom
    try:
        ctx.add_basemap(ax, source=ctx.providers.Esri.WorldImagery,
                        zoom='auto', attribution=False, zorder=1)
    except Exception:
        ax.set_facecolor('#1a3a5c')  # fallback ocean blue if tiles unavailable

    # Profile scatter (bright yellow — stands out on satellite)
    ax.scatter(xs, ys, s=10, c='#ffee58', alpha=0.80, zorder=4,
               edgecolors='#f57f17', linewidths=0.4,
               label=f'Profiles (n={len(lats)})')

    # Current boundary — solid red
    if current_bounds:
        c_lo_min, c_lo_max, c_la_min, c_la_max = current_bounds
        cx0, cy0 = ll2m(c_lo_min, c_la_min)
        cx1, cy1 = ll2m(c_lo_max, c_la_max)
        ax.add_patch(mpatches.Rectangle(
            (cx0, cy0), cx1 - cx0, cy1 - cy0,
            fill=False, edgecolor='#ff1744', linewidth=2.2, zorder=5,
            label='Current boundary'))

    # Proposed boundary — dashed bright green
    px0, py0 = ll2m(p_lo_min, p_la_min)
    px1, py1 = ll2m(p_lo_max, p_la_max)
    ax.add_patch(mpatches.Rectangle(
        (px0, py0), px1 - px0, py1 - py0,
        fill=False, edgecolor='#00e676', linewidth=2.2, linestyle='--', zorder=5,
        label='Proposed boundary'))

    # ── Tick labels in decimal degrees ────────────────────────────────────
    ax.xaxis.set_major_formatter(mticker.FuncFormatter(
        lambda x, _: f'{to_ll.transform(x, 0)[0]:.2f}'))
    ax.yaxis.set_major_formatter(mticker.FuncFormatter(
        lambda y, _: f'{to_ll.transform(0, y)[1]:.2f}'))

    ax.tick_params(labelsize=7, colors='#eeeeee')
    for spine in ax.spines.values():
        spine.set_edgecolor('#555555')

    ax.set_xlabel('Longitude', fontsize=8, color='#cccccc')
    ax.set_ylabel('Latitude',  fontsize=8, color='#cccccc')
    ax.set_title('QARTOD USVI Regional Boundary', fontsize=9,
                 fontweight='bold', color='white', pad=6)
    ax.legend(loc='upper right', fontsize=7, framealpha=0.85,
              facecolor='#1e1e1e', labelcolor='white', edgecolor='#444444')

    fig.tight_layout(pad=0.6)

    buf = io.BytesIO()
    fig.savefig(buf, format='png', dpi=130, facecolor=fig.get_facecolor())
    plt.close(fig)
    buf.seek(0)
    return base64.b64encode(buf.read()).decode('ascii')


def analyze_region_coverage(nc_dir, base_dir):
    """
    Check whether the deployment's profile track falls within the configured
    USVI QARTOD region.  Returns a dict included in PREFLIGHT_JSON.
    """
    print('', flush=True)
    print('Checking regional QC boundary coverage…', flush=True)

    lats, lons = read_profile_positions(nc_dir)
    if not lats:
        print('  No profile positions found — skipping boundary check.', flush=True)
        return {'coverage_ok': True, 'note': 'No profile positions found'}

    region_data, boundaries_path = read_region_boundaries(base_dir)
    current_bounds = get_region_bounds(region_data)

    n_out = 0
    if current_bounds:
        lo_min, lo_max, la_min, la_max = current_bounds
        n_out = sum(1 for la, lo in zip(lats, lons)
                    if not (lo_min <= lo <= lo_max and la_min <= la <= la_max))

    coverage_ok = (current_bounds is not None) and (n_out == 0)

    result = {
        'coverage_ok':     coverage_ok,
        'n_profiles':      len(lats),
        'n_outside':       n_out,
        'data_lat':        [round(min(lats), 4), round(max(lats), 4)],
        'data_lon':        [round(min(lons), 4), round(max(lons), 4)],
        'current_lat':     [current_bounds[2], current_bounds[3]] if current_bounds else None,
        'current_lon':     [current_bounds[0], current_bounds[1]] if current_bounds else None,
        'boundaries_path': boundaries_path,
    }

    if coverage_ok:
        print(f'  All {len(lats)} profiles fall within the USVI boundary.', flush=True)
    else:
        lat_min, lat_max, lon_min, lon_max = compute_proposed_boundary(lats, lons)
        proposed_bounds = (lon_min, lon_max, lat_min, lat_max)

        result['proposed_lat']         = [lat_min, lat_max]
        result['proposed_lon']         = [lon_min, lon_max]
        result['boundaries_content']   = build_updated_boundaries_yml(
            region_data, lat_min, lat_max, lon_min, lon_max)
        result['map_base64']           = generate_region_map(
            lats, lons, current_bounds, proposed_bounds)

        print(f'  WARNING: {n_out} of {len(lats)} profiles fall outside the current USVI boundary.',
              flush=True)
        print(f'    Data extent:     lat [{min(lats):.3f}, {max(lats):.3f}]  '
              f'lon [{min(lons):.3f}, {max(lons):.3f}]', flush=True)
        print(f'    Proposed bounds: lat [{lat_min}, {lat_max}]  '
              f'lon [{lon_min}, {lon_max}]', flush=True)

    return result


# ── Config status helpers ─────────────────────────────────────────────────────

def config_entry(config_dir, fname, new_content):
    fpath    = os.path.join(config_dir, fname)
    exists   = os.path.isfile(fpath)
    existing = None
    if exists:
        try:
            with open(fpath, 'r', encoding='utf-8') as f:
                existing = f.read()
        except Exception:
            pass
    if not exists:
        action = 'create'
    elif existing != new_content:
        action = 'update'
    else:
        action = 'unchanged'
    return {
        'content':          new_content,
        'exists':           exists,
        'existing_content': existing,
        'action':           action,
    }


# ── Main ──────────────────────────────────────────────────────────────────────

def main(args):
    base_dir   = args.base_dir
    deployment = args.deployment
    apply_json = args.apply
    apply_file = getattr(args, 'apply_file', '')

    year       = deployment.split('-')[1][:4]
    config_dir = os.path.join(base_dir, 'deployments', year, deployment, 'config', 'qc')

    # ── Apply mode ────────────────────────────────────────────────────────────
    if apply_file or apply_json:
        try:
            if apply_file:
                with open(apply_file, 'r', encoding='utf-8') as _f:
                    data = json.load(_f)
            else:
                data = json.loads(apply_json)
        except (json.JSONDecodeError, OSError) as e:
            print(f'ERROR: Invalid JSON: {e}', flush=True)
            return 1
        os.makedirs(config_dir, exist_ok=True)
        config_dir_real = os.path.realpath(config_dir)
        for fname, info in data.get('configs', {}).items():
            fpath = os.path.realpath(os.path.join(config_dir, fname))
            if fpath != config_dir_real and not fpath.startswith(config_dir_real + os.sep):
                print(f'  ERROR: Invalid config filename: {fname!r}', flush=True)
                continue
            action  = info.get('action', 'unchanged')
            content = info.get('content', '')
            if action in ('create', 'update'):
                with open(fpath, 'w', encoding='utf-8') as f:
                    f.write(content)
                verb = 'Created' if action == 'create' else 'Updated'
                print(f'  {verb}: {fname}', flush=True)
            else:
                print(f'  Unchanged: {fname}', flush=True)

        # Optional: update global regional_boundaries.yml if user confirmed.
        # The write path is always recomputed here, never taken from the
        # request body — `read_region_boundaries()` below computes the exact
        # same path, so this is a no-op for any legitimate request and just
        # removes the client's ability to redirect the write.
        rc = data.get('region_coverage', {})
        if rc.get('update_requested'):
            bpath = os.path.join(base_dir, 'qc', 'config', 'global_regional', 'regional_boundaries.yml')
            try:
                # If user edited the boundary values, rebuild YAML from their inputs;
                # otherwise fall back to the auto-proposed content.
                user_lat = rc.get('user_lat')   # [lat_min, lat_max] or None
                user_lon = rc.get('user_lon')   # [lon_min, lon_max] or None
                if user_lat and user_lon:
                    region_data, _ = read_region_boundaries(base_dir)
                    content = build_updated_boundaries_yml(
                        region_data,
                        float(user_lat[0]), float(user_lat[1]),
                        float(user_lon[0]), float(user_lon[1]),
                    )
                else:
                    content = rc.get('boundaries_content', '')
                with open(bpath, 'w', encoding='utf-8') as f:
                    f.write(content)
                print(f'  Updated: regional_boundaries.yml (global USVI boundary)', flush=True)
            except OSError as e:
                print(f'  ERROR: Could not write regional_boundaries.yml: {e}', flush=True)

        print('', flush=True)
        print('Pre-flight config applied successfully.', flush=True)
        return 0

    # ── Analysis mode ─────────────────────────────────────────────────────────
    print(f'=== Pre-flight QC Config Check: {deployment} ===', flush=True)
    print('', flush=True)

    nc_path = find_profile_nc(base_dir, deployment)
    if not nc_path:
        print('ERROR: No profile NC files found in gncutils_slocum_nc_output/.', flush=True)
        print('       Run Stage 2a (DAT → Profile NC) before Stage 3.', flush=True)
        return 1
    print(f'Reading instrument metadata from: {os.path.basename(nc_path)}', flush=True)

    instruments = read_instruments(nc_path)
    sensors     = detect_sensors(instruments)
    oxygen_vars = get_oxygen_vars(nc_path) if sensors['oxygen'] else []

    # ── Print sensor summary ──────────────────────────────────────────────────
    print('', flush=True)
    print('Instruments detected:', flush=True)
    labels = {'ctd': 'CTD   ', 'oxygen': 'Oxygen', 'ph': 'pH    '}
    for stype in ('ctd', 'oxygen', 'ph'):
        s = sensors[stype]
        if s:
            print(f'  {labels[stype]}  {s["maker"]} {s["model"]}  ({s["instrument_var"]})',
                  flush=True)
        else:
            print(f'  {labels[stype]}  — not detected', flush=True)

    if sensors['oxygen'] and oxygen_vars:
        print('', flush=True)
        print('Oxygen variables found in NC file:', flush=True)
        for v in oxygen_vars:
            print(f'  {v}', flush=True)
    elif sensors['oxygen'] and not oxygen_vars:
        print('', flush=True)
        print('WARNING: Oxygen instrument detected but no oxygen variables found in NC file.',
              flush=True)

    # ── Regional boundary coverage check ─────────────────────────────────────
    nc_dir = os.path.dirname(nc_path)
    region_coverage = analyze_region_coverage(nc_dir, base_dir)

    # ── Build config file contents ────────────────────────────────────────────
    configs = {}

    if sensors['oxygen'] or sensors['ph']:
        configs['time_shift.yml'] = config_entry(
            config_dir, 'time_shift.yml',
            build_time_shift_yml(sensors, oxygen_vars))

    configs['qctests.yml'] = config_entry(
        config_dir, 'qctests.yml',
        build_qctests_yml(sensors))

    configs['ctd_hysteresis.yml'] = config_entry(
        config_dir, 'ctd_hysteresis.yml',
        build_ctd_hysteresis_yml())

    # ── Print config summary ──────────────────────────────────────────────────
    print('', flush=True)
    print(f'Config directory: {config_dir}', flush=True)
    print('', flush=True)
    print('Config files:', flush=True)
    any_changes = False
    for fname, info in configs.items():
        action = info['action'].upper()
        print(f'  {fname}  ->  {action}', flush=True)
        if info['action'] != 'unchanged':
            any_changes = True

    if not any_changes:
        print('', flush=True)
        print('All config files are already up to date — no changes needed.', flush=True)

    # ── Output JSON for frontend confirmation UI ──────────────────────────────
    result = {
        'deployment':     deployment,
        'config_dir':     config_dir,
        'sensors':        sensors,
        'oxygen_vars':    oxygen_vars,
        'configs':        configs,
        'any_changes':    any_changes,
        'region_coverage': region_coverage,
    }
    print('', flush=True)
    print(f'=== PREFLIGHT_JSON ==={json.dumps(result)}', flush=True)
    return 0


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('base_dir',    help='Pipeline root directory (base_dir)')
    parser.add_argument('deployment',  help='Glider deployment name (glider-YYYYmmddTHHMM)')
    parser.add_argument('--apply', default='', metavar='JSON',
                        help='JSON string from analysis phase — writes config files when set')
    parser.add_argument('--apply-file', default='', metavar='PATH',
                        help='Path to JSON file from analysis phase (avoids command-line length limits)')
    sys.exit(main(parser.parse_args()))
